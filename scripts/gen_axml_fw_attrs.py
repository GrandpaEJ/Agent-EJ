#!/usr/bin/env python3
"""Generate src/android/axml/axml_fw_attrs.h from the Android SDK.

Binary XML refers to android:* attributes by framework resource ID, not by
name, and stores enum/flag attributes as integers. The encoder needs the full
public attr table (name -> ID), each attr's declared format, and every
enum/flag value to turn decoded text back into what aapt2 would have written.

usage: ANDROID_HOME=<sdk> scripts/gen_axml_fw_attrs.py [platform] > src/android/axml/axml_fw_attrs.h
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

FMT_BITS = {"string": 1, "integer": 2, "boolean": 4, "color": 8,
            "float": 16, "dimension": 32, "fraction": 64, "reference": 128}
BASE = 0x01010000


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '\\0"'


def main():
    sdk = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if not sdk:
        sys.exit("set ANDROID_HOME")
    platform = sys.argv[1] if len(sys.argv) > 1 else "android-36"
    vals_dir = os.path.join(sdk, "platforms", platform, "data", "res", "values")

    pub = {}
    text = open(os.path.join(vals_dir, "public-final.xml"), encoding="utf-8").read()
    for name, rid in re.findall(r'<public type="attr" name="([^"]+)" id="(0x[0-9a-f]+)"', text):
        pub[int(rid, 16)] = name

    fmt, vals = {}, {}
    for f in ("attrs.xml", "attrs_manifest.xml"):
        for a in ET.parse(os.path.join(vals_dir, f)).getroot().iter("attr"):
            n = a.get("name").removeprefix("android:")
            kids = [(c.tag == "flag", c.get("name"), int(c.get("value"), 0) & 0xFFFFFFFF)
                    for c in a if c.tag in ("enum", "flag")]
            if a.get("format") and n not in fmt:
                fmt[n] = a.get("format")
            if kids and n not in vals:
                vals[n] = kids

    count = max(pub) - BASE + 1
    names = [pub.get(BASE + i, "") for i in range(count)]
    fmts = []
    for n in names:
        bits = 0
        for part in fmt.get(n, "").split("|"):
            bits |= FMT_BITS.get(part, 0)
        fmts.append(bits)

    # Flags sorted by value, largest first: the decoder's greedy decomposition
    # then prefers multi-bit masks (adjustNothing=0x30 over adjustPan=0x20).
    enums = []
    for i, n in enumerate(names):
        kids = vals.get(n, [])
        flags = sorted((k for k in kids if k[0]), key=lambda k: k[2], reverse=True)
        for is_flag, en, ev in [k for k in kids if not k[0]] + flags:
            enums.append((i | (0x8000 if is_flag else 0), ev, en))

    out = sys.stdout
    out.write(f"/* Generated by scripts/gen_axml_fw_attrs.py from the Android SDK\n"
              f" * ({platform}/data/res/values). Do not edit by hand. */\n")
    out.write("#ifndef AXML_FW_ATTRS_H\n#define AXML_FW_ATTRS_H\n#include <stdint.h>\n\n")
    out.write(f"#define AXML_FW_ATTR_BASE 0x{BASE:08x}u\n#define AXML_FW_ATTR_COUNT {count}\n")
    out.write(f"#define AXML_FW_ENUM_COUNT {len(enums)}\n\n")
    out.write("/* axml_fw_attr_fmts[] uses the AXML_FMT_* bits from format_axml_enum.h. */\n")
    out.write("\n/* Attr names in ID order (index = id - BASE), \"\" for unassigned IDs. */\n")
    out.write("static const char axml_fw_attr_names[] =\n")
    for i in range(0, count, 6):
        out.write("    " + " ".join(c_str(n) for n in names[i:i + 6]) + "\n")
    out.write("    ;\n\nstatic const uint8_t axml_fw_attr_fmts[AXML_FW_ATTR_COUNT] = {\n")
    for i in range(0, count, 24):
        out.write("    " + ",".join(str(b) for b in fmts[i:i + 24]) + ",\n")
    out.write("};\n\n/* Enum/flag values: attr index (bit 15 = flag), grouped by attr. */\n")
    out.write("static const uint16_t axml_fw_enum_attr[AXML_FW_ENUM_COUNT] = {\n")
    for i in range(0, len(enums), 16):
        out.write("    " + ",".join(f"0x{e[0]:04x}" for e in enums[i:i + 16]) + ",\n")
    out.write("};\nstatic const uint32_t axml_fw_enum_val[AXML_FW_ENUM_COUNT] = {\n")
    for i in range(0, len(enums), 8):
        out.write("    " + ",".join(f"0x{e[1]:08x}" for e in enums[i:i + 8]) + ",\n")
    out.write("};\nstatic const char axml_fw_enum_names[] =\n")
    for i in range(0, len(enums), 6):
        out.write("    " + " ".join(c_str(e[2]) for e in enums[i:i + 6]) + "\n")
    out.write("    ;\n\n#endif\n")


if __name__ == "__main__":
    main()
